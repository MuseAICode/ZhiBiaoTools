const SEQUENCES = ['0123456789', '9876543210', 'abcdefghijklmnopqrstuvwxyz', 'zyxwvutsrqponmlkjihgfedcba', 'qwertyuiopasdfghjklzxcvbnm'];

export function isWeakPassword(password: string): boolean {
  const lower = password.toLowerCase();
  if (WEAK_PASSWORDS.has(lower)) return true;
  if (/^(.)\1+$/u.test(lower)) return true;
  return SEQUENCES.some((sequence) => sequence.includes(lower));
}
